"""Write the README results block (retrieval metrics, radar precision, latest-FY benchmark).

Usage: python -m scripts.readme_results  (or `make readme`). Everything between the
RESULTS markers in README.md is regenerated from the committed snapshot and eval files.
"""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd
import yaml

from secanalyst.config import REPO_ROOT
from secanalyst.warehouse.quality import KEY_RATIOS, _fmt

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"
RADAR_CSV = REPO_ROOT / "docs" / "design" / "radar_labelled_hits.csv"
HOLDOUT_ROUND = 2  # fresh draw, never used for tuning (see docs/design/risk-diligence-notes.md)
FILTER_LABELS = [
    (("ticker", "fy"), "company + fiscal year"),
    (("ticker",), "company only"),
    ((), "no filter"),
]


def render_retrieval_table(results: dict[tuple[str, ...], dict], n: int) -> str:
    lines = [
        f"**Retrieval** ({n} author-labelled questions, each aimed at a latest-year filing)",
        "",
        "| Filters set by the user | recall@5 | MRR |",
        "|---|--:|--:|",
    ]
    for keys, label in FILTER_LABELS:
        r = results[keys]
        lines.append(f"| {label} | {r['recall_at_5']:.3f} | {r['mrr']:.3f} |")
    return "\n".join(lines)


def radar_precision(labels: pd.DataFrame, round_: int = HOLDOUT_ROUND) -> tuple[int, int]:
    """(true positives, sample size) of one labelling round."""
    sub = labels[labels["round"] == round_]
    return int((sub["label"] == "y").sum()), len(sub)


def render_radar_line(tp: int, n: int) -> str:
    return (
        f"**Red-flag radar precision:** {tp / n:.3f} ({tp}/{n}) on an out-of-sample holdout, "
        "one labeller, interval about +/-0.10."
    )


def render_benchmark_table(ratios: pd.DataFrame) -> str:
    """Latest fiscal year per company, key ratios; n/a and n/m shown as such, never imputed."""
    latest = ratios.sort_values("period_end").groupby("ticker").tail(1)
    keep = ratios.merge(latest[["ticker", "fiscal_year_label"]], on=["ticker", "fiscal_year_label"])
    head = ["Ticker", "FY", "Period end"] + [label for _, label, _ in KEY_RATIOS]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * 3 + "--:|" * len(KEY_RATIOS)]
    for ticker, g in keep.groupby("ticker", sort=True):
        by = g.set_index("ratio")
        cells = [
            ticker,
            g["fiscal_year_label"].iloc[0],
            str(pd.Timestamp(g["period_end"].iloc[0]).date()),
        ]
        cells += [_fmt(by.loc[n, "value"], by.loc[n, "status"], kind) for n, _, kind in KEY_RATIOS]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_block(results, n_questions, radar: tuple[int, int], ratios, as_of: str) -> str:
    return "\n\n".join(
        [
            f"*Generated by `make readme` from the committed snapshot (data as of {as_of}).*",
            render_retrieval_table(results, n_questions),
            render_radar_line(*radar),
            "**Benchmark, latest fiscal year per company** (fiscal years end in different months: "
            "compare by label and period end)\n\n" + render_benchmark_table(ratios),
        ]
    )


def replace_block(readme: str, block: str) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(readme):
        raise ValueError(f"README has no {START} ... {END} block")
    return pattern.sub(lambda _: f"{START}\n{block}\n{END}", readme, count=1)


def collect():
    from secanalyst.retrieval.embedding import FastEmbedder
    from secanalyst.retrieval.search import Index, evaluate
    from secanalyst.warehouse import snapshot

    qs = yaml.safe_load((REPO_ROOT / "data" / "eval" / "retrieval_eval.yaml").read_text())
    qs = qs["questions"]
    idx, embedder = Index.load(snapshot.SNAPSHOT_DIR), FastEmbedder()
    results = {keys: evaluate(idx, qs, embedder, keys) for keys, _ in FILTER_LABELS}
    con = snapshot.load_snapshot()
    as_of = con.execute("SELECT value FROM meta WHERE key = 'as_of'").fetchone()[0]
    ratios = con.execute("SELECT * FROM fact_ratios").df()
    radar = radar_precision(pd.read_csv(RADAR_CSV))
    return results, len(qs), radar, ratios, as_of


def main(readme: Path = REPO_ROOT / "README.md") -> None:
    block = render_block(*collect())
    readme.write_text(replace_block(readme.read_text(encoding="utf-8"), block), encoding="utf-8")
    print(f"updated {readme}")


if __name__ == "__main__":
    main()
